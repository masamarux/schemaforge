def test_generate_command_writes_schemas_file():
    with runner.isolated_filesystem():
        with open("schemaforge.schema", "w", encoding="utf-8") as schema_file:
            schema_file.write(
                """
                model User {
                  id UUID @id @default(uuid())
                  email String
                }
                """
            )

        result = runner.invoke(app, ["generate"])

        assert result.exit_code == 0
        assert "Generated Pydantic schemas: app/db/generated/schemas.py" in result.stdout
        assert "class UserCreate(BaseModel):" in open(
            "app/db/generated/schemas.py", encoding="utf-8"
        ).read()


